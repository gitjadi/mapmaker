"""Generate web/src/shared/*.ts from the desktop app's Python modules, so the browser and
desktop versions share the same symbols, text presets, colours, themes and background maps.

Run from the repository root:   python web/tools/gen_shared.py
"""
from __future__ import annotations

import importlib.util
import json
import sys
import types
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "web" / "src" / "shared"
PKG = ROOT / "mapmaker"


def load(name: str):
    """Import mapmaker.<name> straight from its file, without the package __init__ (no Qt needed)."""
    if "mapmaker" not in sys.modules:
        pkg = types.ModuleType("mapmaker")
        pkg.__path__ = [str(PKG)]
        pkg.__version__ = "web"
        sys.modules["mapmaker"] = pkg
    spec = importlib.util.spec_from_file_location(f"mapmaker.{name}", PKG / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[f"mapmaker.{name}"] = mod
    spec.loader.exec_module(mod)
    return mod


def ts(name: str, value, typ: str = "") -> str:
    return f"export const {name}{(': ' + typ) if typ else ''} = {json.dumps(value, ensure_ascii=False, indent=1)};\n\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    head = "// Generated by web/tools/gen_shared.py from the desktop app – do not edit by hand.\n\n"

    sym = load("symbols")
    symbols = {k: {"label": v[0], "category": v[1], "anchor": list(v[2]), "body": v[3]} for k, v in sym.SYMBOLS.items()}
    (OUT / "symbols.ts").write_text(
        head + "export interface SymbolDef { label: string; category: string; anchor: [number, number]; body: string }\n\n"
        + ts("SYMBOLS", symbols, "Record<string, SymbolDef>") + ts("SYMBOL_CATEGORIES", sym.CATEGORIES, "string[]"),
        encoding="utf-8")

    st = load("styles")
    out = head
    out += ts("SANS", st.SANS) + ts("SERIF", st.SERIF) + ts("FONTS", st.FONTS, "Record<string, string[]>")
    out += ts("TEXT_BASE", st._BASE, "Record<string, any>")
    out += ts("TEXT_PRESETS", {k: {"label": v[0], "style": v[1]} for k, v in st.TEXT_PRESETS.items()},
              "Record<string, { label: string; style: Record<string, any> }>")
    out += ts("SWATCHES", st.SWATCHES) + ts("PALETTES", st.PALETTES) + ts("DASHES", st.DASHES, "Record<string, string>")
    out += ts("DESIGN_DEFAULTS", st.DESIGN_DEFAULTS, "Record<string, any>")
    out += ts("THEMES", st.THEMES, "Record<string, any>")
    out += ts("LINE_STYLE", st.default_line_style(), "Record<string, any>")
    out += ts("AREA_STYLE", st.default_area_style(), "Record<string, any>")
    (OUT / "styles.ts").write_text(out, encoding="utf-8")

    # tiles.py imports numpy/PIL; read the list without importing the heavy parts if they are missing
    try:
        tl = load("tiles")
        basemaps = [asdict(b) for b in tl.BASEMAPS]
        default = tl.DEFAULT_BASEMAP
    except ImportError as e:
        sys.exit(f"tiles.py needs its dependencies to be importable ({e}); run from the desktop app's .venv")
    (OUT / "basemaps.ts").write_text(
        head + "import type { TileSourceDef } from '../tiles';\n\n"
        + ts("BASEMAPS", basemaps, "TileSourceDef[]") + ts("DEFAULT_BASEMAP", default), encoding="utf-8")
    print("wrote", ", ".join(p.name for p in sorted(OUT.glob("*.ts"))))


if __name__ == "__main__":
    main()
